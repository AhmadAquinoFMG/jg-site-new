"""Turn a raw Lead Prosper lead into a normalized Meta attribution record.

Field layout this understands (observed on the FMG landers, Oct 2026):

    ad id        fb_adid | source_id | utm_content
    ad set id    utm_term
    campaign id  utm_campaign
    ad name      lp_subid4 | utm_creative
    ad set name  lp_subid3 | utm_adgroup | lp_subid5
    campaign nm  lp_subid2 | subid | lp_subid6
    placement    ms_placement | utm_placement | lp_subid7
    publisher    ms_publisher | lp_subid8
    click        fbclid, fbc, fbp
    dedupe       event_id (UUID generated by the lander)
    everflow     affid, oid, ef_transaction_id

Every value is checked for unresolved Meta macros (literal "{{...}}") and
for the right shape before it is trusted. Problems are reported in
`issues` so the trace can say *why* a lead cannot be attributed.
"""
from __future__ import annotations

import re
from dataclasses import dataclass, field, asdict
from typing import Any

META_ID = re.compile(r"^\d{10,20}$")
MACRO = re.compile(r"\{\{.*?\}\}")
FBCLID = re.compile(r"^(IwAR|IwY|IwZ|PAAa|PAZX|IwcG)[A-Za-z0-9_-]{20,}$")
FBC = re.compile(r"^fb\.\d\.\d{10,13}\..+$")
FBP = re.compile(r"^fb\.\d\.\d{10,13}\.\d+$")
# Accepted event_id shapes: a UUID (United Settlement landers mint one per lead)
# or 'lead-<n>' (jgdebtrelief.com derives it from its own leads.id, the same id
# its TikTok and CallGrid CAPI events use).
UUID = re.compile(r"^(?:[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}|lead-\d+)$", re.I)

AD_ID_FIELDS = ("fb_adid", "source_id", "utm_content")
ADSET_ID_FIELDS = ("utm_term",)
CAMPAIGN_ID_FIELDS = ("utm_campaign",)
AD_NAME_FIELDS = ("lp_subid4", "utm_creative")
ADSET_NAME_FIELDS = ("lp_subid3", "utm_adgroup", "lp_subid5")
CAMPAIGN_NAME_FIELDS = ("lp_subid2", "subid", "lp_subid6")
PLACEMENT_FIELDS = ("ms_placement", "utm_placement", "lp_subid7")
PUBLISHER_FIELDS = ("ms_publisher", "lp_subid8")


@dataclass
class Attribution:
    lead_id: str
    lead_date_ms: int | None
    campaign_id_lp: int | None
    campaign_name_lp: str | None
    supplier: str | None
    status: str | None
    cost: float | None
    revenue: float | None
    buyers: list[dict[str, Any]] = field(default_factory=list)

    # Meta identity
    meta_ad_id: str | None = None
    meta_adset_id: str | None = None
    meta_campaign_id: str | None = None
    meta_ad_name: str | None = None
    meta_adset_name: str | None = None
    meta_campaign_name: str | None = None
    placement: str | None = None
    publisher: str | None = None
    meta_id_source: str | None = None  # which field the ad id came from
    confidence: str | None = None      # "high" (dedicated id field) | "low" (fallback slot) | None

    # Click / dedupe
    fbclid: str | None = None
    fbc: str | None = None
    fbc_reconstructed: bool = False
    fbp: str | None = None
    event_id: str | None = None

    # Everflow
    affid: str | None = None
    oid: str | None = None
    ef_transaction_id: str | None = None
    landing_page_url: str | None = None
    utm_source: str | None = None

    # Quality
    attributable: bool = False
    issues: list[str] = field(default_factory=list)

    def to_dict(self) -> dict[str, Any]:
        return asdict(self)


def _clean(v: Any) -> str | None:
    if v is None:
        return None
    s = str(v).strip()
    if not s or s.lower() in ("null", "none", "undefined", "n/a", "{}", "[]"):
        return None
    return s


def _first(ld: dict, fields: tuple[str, ...], validator=None, issues: list[str] | None = None,
           label: str = "") -> tuple[str | None, str | None]:
    """Return (value, field_name) for the first field whose value is valid."""
    macro_hits = []
    for f in fields:
        v = _clean(ld.get(f))
        if v is None:
            continue
        if MACRO.search(v):
            macro_hits.append(f"{f}={v}")
            continue
        if validator is None or validator(v):
            return v, f
    if macro_hits and issues is not None:
        issues.append(f"unresolved_macro:{label}:" + ",".join(macro_hits))
    return None, None


def normalize(lead: dict) -> Attribution:
    ld: dict = lead.get("lead_data") or {}
    issues: list[str] = []

    supplier = (lead.get("supplier") or {}).get("name")
    buyers = [{
        "id": b.get("id"), "name": b.get("name"),
        "outcome": ((b.get("outcome") or {}).get("status") if isinstance(b.get("outcome"), dict)
                    else b.get("outcome")),
        "price": b.get("price") or b.get("revenue"),
    } for b in (lead.get("buyers") or [])]

    try:
        lead_date_ms = int(lead.get("lead_date_ms")) if lead.get("lead_date_ms") else None
    except (TypeError, ValueError):
        lead_date_ms = None

    a = Attribution(
        lead_id=str(lead.get("id")),
        lead_date_ms=lead_date_ms,
        campaign_id_lp=lead.get("campaign_id"),
        campaign_name_lp=lead.get("campaign_name"),
        supplier=supplier,
        status=lead.get("status"),
        cost=lead.get("cost"),
        revenue=lead.get("revenue"),
        buyers=buyers,
        affid=_clean(ld.get("affid")),
        oid=_clean(ld.get("oid")),
        ef_transaction_id=_clean(ld.get("ef_transaction_id")),
        landing_page_url=_clean(ld.get("landing_page_url")),
        utm_source=_clean(ld.get("utm_source")),
        issues=issues,
    )

    a.meta_ad_id, a.meta_id_source = _first(ld, AD_ID_FIELDS, META_ID.match, issues, "ad_id")
    a.meta_adset_id, _ = _first(ld, ADSET_ID_FIELDS, META_ID.match, issues, "adset_id")
    a.meta_campaign_id, _ = _first(ld, CAMPAIGN_ID_FIELDS, META_ID.match, issues, "campaign_id")
    a.meta_ad_name, _ = _first(ld, AD_NAME_FIELDS, None, issues, "ad_name")
    a.meta_adset_name, _ = _first(ld, ADSET_NAME_FIELDS, None, issues, "adset_name")
    a.meta_campaign_name, _ = _first(ld, CAMPAIGN_NAME_FIELDS, None, issues, "campaign_name")
    a.placement, _ = _first(ld, PLACEMENT_FIELDS, None, issues, "placement")
    a.publisher, _ = _first(ld, PUBLISHER_FIELDS, None, issues, "publisher")

    # Names landing in id slots or vice versa (seen on the chat-bot lander, where
    # lp_subid4 / lp_subid2 hold numeric ids). Use them as a low-confidence fallback.
    if a.meta_ad_name and META_ID.match(a.meta_ad_name):
        issues.append("name_slot_holds_numeric_id:ad_name")
        if not a.meta_ad_id:
            a.meta_ad_id, a.meta_id_source = a.meta_ad_name, "lp_subid4(name slot)"
            a.confidence = "low"
            issues.append("ad_id_from_name_slot")
        a.meta_ad_name = None
    if a.meta_campaign_name and META_ID.match(a.meta_campaign_name):
        issues.append("name_slot_holds_numeric_id:campaign_name")
        if not a.meta_campaign_id:
            a.meta_campaign_id = a.meta_campaign_name
        a.meta_campaign_name = None
    if a.meta_ad_id and a.confidence is None:
        a.confidence = "high"

    # Click identifiers
    fbclid = _clean(ld.get("fbclid"))
    if fbclid and MACRO.search(fbclid):
        issues.append("unresolved_macro:fbclid")
        fbclid = None
    a.fbclid = fbclid
    fbc = _clean(ld.get("fbc"))
    if fbc and FBC.match(fbc):
        a.fbc = fbc
    elif fbclid and lead_date_ms:
        # Meta's documented format: fb.<subdomainIndex>.<creationTime ms>.<fbclid>
        a.fbc = f"fb.1.{lead_date_ms}.{fbclid}"
        a.fbc_reconstructed = True
    fbp = _clean(ld.get("fbp"))
    a.fbp = fbp if fbp and FBP.match(fbp) else None

    ev = _clean(ld.get("event_id"))
    a.event_id = ev
    if not ev:
        issues.append("missing_event_id")
    elif not UUID.match(ev):
        issues.append("event_id_not_uuid")

    if not a.meta_ad_id:
        issues.append("missing_ad_id")
    if not a.fbclid and not a.fbc:
        issues.append("missing_click_id")
    if a.utm_source and a.utm_source.lower() not in ("facebook", "fb", "meta", "instagram", "ig"):
        issues.append(f"non_meta_source:{a.utm_source}")

    a.attributable = a.meta_ad_id is not None
    return a


def summarize_issues(records: list[Attribution]) -> dict[str, int]:
    counts: dict[str, int] = {}
    for r in records:
        for i in r.issues:
            key = i.split(":")[0] + (":" + i.split(":")[1] if i.startswith("unresolved_macro") else "")
            counts[key] = counts.get(key, 0) + 1
    return dict(sorted(counts.items(), key=lambda kv: -kv[1]))
